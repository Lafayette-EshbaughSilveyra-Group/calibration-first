def resolve_sim_block(
    record: Dict[str, Any],
    sim_var: str,
) -> Optional[Any]:
    if sim_var in record:
        return record[
            sim_var
        ]

    wanted = sim_var.strip()

    by_stripped = {
        str(key).strip(): value
        for key, value
        in record.items()
    }

    if wanted in by_stripped:
        return by_stripped[
            wanted
        ]

    by_lower = {
        str(key).strip().lower(): value
        for key, value
        in record.items()
    }

    if wanted.lower() in by_lower:
        return by_lower[
            wanted.lower()
        ]

    matches = [
        (
            str(key),
            value,
        )
        for key, value
        in record.items()
        if str(
            key
        ).strip().endswith(
            wanted
        )
    ]

    if len(
        matches
    ) == 1:
        return matches[
            0
        ][1]

    if len(
        matches
    ) > 1:
        return sorted(
            matches,
            key=lambda item: len(
                item[0]
            ),
        )[0][1]

    return None


def extract_stat_value(
    record: Dict[str, Any],
    feature_candidates: Sequence[str],
) -> Optional[float]:
    """
    Extract one numeric simulation statistic.

    The newly generated calibration summaries expose "mean", which is preferred.
    Additional aliases are retained for compatibility with older dataset files.
    """
    stat_keys = (
        "mean",
        "average",
        "avg",
        "value",
        "min",
        "max",
        "std",
    )

    for candidate in feature_candidates:
        block = resolve_sim_block(
            record,
            candidate,
        )

        if isinstance(
            block,
            dict,
        ):
            for stat_key in stat_keys:
                numeric_value = as_float(
                    block.get(
                        stat_key
                    )
                )

                if numeric_value is not None:
                    return numeric_value

        else:
            numeric_value = as_float(
                block
            )

            if numeric_value is not None:
                return numeric_value

    for container_key in (
        "features",
        "summary",
        "summary_stats",
        "stats",
        "outputs",
    ):
        container = record.get(
            container_key
        )

        if not isinstance(
            container,
            dict,
        ):
            continue

        for candidate in feature_candidates:
            block = resolve_sim_block(
                container,
                candidate,
            )

            if isinstance(
                block,
                dict,
            ):
                for stat_key in stat_keys:
                    numeric_value = as_float(
                        block.get(
                            stat_key
                        )
                    )

                    if numeric_value is not None:
                        return numeric_value

            else:
                numeric_value = as_float(
                    block
                )

                if numeric_value is not None:
                    return numeric_value

    return None


