# EnergyPlus runtime aggregation
# ---------------------------------------------------------------------------

def load_energyplus_runtime_by_k(
    master_rows: Sequence[
        tuple[
            RawExample,
            Dict[str, int],
        ]
    ],
    runtime_jobs: Dict[
        str,
        Dict[str, Any],
    ],
    config: CalibrationConfig,
) -> Dict[
    str,
    Dict[str, Any],
]:
    """
    Aggregate measured EnergyPlus runtimes for each k grid.

    Because every smaller grid is a subset of the k=15 master grid, the
    cumulative compute time for k is the sum of the measured durations of the
    exact EnergyPlus simulations included in that subset.
    """
    summaries: Dict[
        str,
        Dict[str, Any],
    ] = {
        k_name: {
            "timed_simulation_jobs": 0,
            "successful_simulation_jobs": 0,
            "energyplus_compute_seconds": 0.0,
        }
        for k_name
        in config.level_sets
    }

    allowed_level_sets = {
        k_name: set(
            levels
        )
        for k_name, levels
        in config.level_sets.items()
    }

    for row, levels in master_rows:
        job = runtime_jobs.get(
            row.example_id
        )

        if not isinstance(
            job,
            dict,
        ):
            continue

        runtime_seconds = as_float(
            job.get(
                "runtime_seconds"
            )
        )

        if runtime_seconds is None:
            continue

        succeeded = bool(
            job.get(
                "succeeded",
                False,
            )
        )

        level_values = tuple(
            levels.values()
        )

        for (
            k_name,
            allowed,
        ) in allowed_level_sets.items():
            if all(
                level in allowed
                for level
                in level_values
            ):
                summary = summaries[
                    k_name
                ]

                summary[
                    "timed_simulation_jobs"
                ] += 1

                summary[
                    "energyplus_compute_seconds"
                ] += runtime_seconds

                if succeeded:
                    summary[
                        "successful_simulation_jobs"
                    ] += 1

    for (
        k_name,
        summary,
    ) in summaries.items():
        expected_jobs = (
            len(
                config.level_sets[
                    k_name
                ]
            )
            ** 4
        )

        timed_jobs = int(
            summary[
                "timed_simulation_jobs"
            ]
        )

        compute_seconds = float(
            summary[
                "energyplus_compute_seconds"
            ]
        )

        summary[
            "expected_simulation_jobs"
        ] = expected_jobs

        summary[
            "runtime_measurement_coverage"
        ] = (
            timed_jobs
            / expected_jobs
            if expected_jobs
            else float(
                "nan"
            )
        )

        summary[
            "mean_energyplus_seconds_per_job"
        ] = (
            compute_seconds
            / timed_jobs
            if timed_jobs
            else float(
                "nan"
            )
        )

    return summaries


