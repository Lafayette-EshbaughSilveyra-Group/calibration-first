def write_labeled_csv(
    path: Path,
    labels_by_k: Dict[
        str,
        List[LabeledExample],
    ],
) -> None:
    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    with path.open(
        "w",
        encoding="utf-8",
        newline="",
    ) as handle:
        writer = csv.DictWriter(
            handle,
            fieldnames=(
                "example_id",
                "calibration_resolution",
                "hvac_label",
                "insulation_label",
                "overall_label",
            ),
        )

        writer.writeheader()

        for k_name in sorted(
            labels_by_k,
            key=k_sort_key,
        ):
            for row in labels_by_k[
                k_name
            ]:
                writer.writerow(
                    {
                        "example_id": row.example_id,
                        "calibration_resolution": row.k_name,
                        "hvac_label": row.hvac_label,
                        "insulation_label": row.insulation_label,
                        "overall_label": row.overall_label,
                    }
                )


