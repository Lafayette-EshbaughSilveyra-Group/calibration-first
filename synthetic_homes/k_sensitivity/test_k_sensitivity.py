def rankdata(
    values: Sequence[float],
) -> List[float]:
    """Average ranks for ties, 1-indexed."""
    sorted_pairs = sorted(
        enumerate(
            values
        ),
        key=lambda pair: pair[1],
    )

    ranks = [
        0.0
    ] * len(
        values
    )

    i = 0

    while i < len(
        sorted_pairs
    ):
        j = i

        while (
            j + 1
            < len(
                sorted_pairs
            )
            and sorted_pairs[
                j + 1
            ][1]
            == sorted_pairs[
                i
            ][1]
        ):
            j += 1

        average_rank = (
            i + 1
            + j + 1
        ) / 2.0

        for index in range(
            i,
            j + 1,
        ):
            ranks[
                sorted_pairs[
                    index
                ][0]
            ] = average_rank

        i = (
            j + 1
        )

    return ranks


def pearson(
    x_values: Sequence[float],
    y_values: Sequence[float],
) -> float:
    if (
        len(
            x_values
        )
        != len(
            y_values
        )
        or len(
            x_values
        )
        < 2
    ):
        return float(
            "nan"
        )

    x_mean = statistics.mean(
        x_values
    )

    y_mean = statistics.mean(
        y_values
    )

    numerator = sum(
        (
            x - x_mean
        )
        * (
            y - y_mean
        )
        for x, y
        in zip(
            x_values,
            y_values,
        )
    )

    x_denominator = math.sqrt(
        sum(
            (
                x - x_mean
            )
            ** 2
            for x
            in x_values
        )
    )

    y_denominator = math.sqrt(
        sum(
            (
                y - y_mean
            )
            ** 2
            for y
            in y_values
        )
    )

    denominator = (
        x_denominator
        * y_denominator
    )

    if math.isclose(
        denominator,
        0.0,
        abs_tol=1e-12,
    ):
        return float(
            "nan"
        )

    return (
        numerator
        / denominator
    )


def spearman(
    x_values: Sequence[float],
    y_values: Sequence[float],
) -> float:
    return pearson(
        rankdata(
            x_values
        ),
        rankdata(
            y_values
        ),
    )


def top_fraction_overlap(
    candidate_scores: Dict[str, float],
    reference_scores: Dict[str, float],
    fraction: float = 0.10,
) -> float:
    common_ids = sorted(
        set(
            candidate_scores
        )
        & set(
            reference_scores
        )
    )

    if not common_ids:
        return float(
            "nan"
        )

    top_n = max(
        1,
        math.ceil(
            len(
                common_ids
            )
            * fraction
        ),
    )

    candidate_top = {
        example_id
        for example_id, _
        in sorted(
            (
                (
                    example_id,
                    candidate_scores[
                        example_id
                    ],
                )
                for example_id
                in common_ids
            ),
            key=lambda pair: pair[1],
            reverse=True,
        )[
            :top_n
        ]
    }

    reference_top = {
        example_id
        for example_id, _
        in sorted(
            (
                (
                    example_id,
                    reference_scores[
                        example_id
                    ],
                )
                for example_id
                in common_ids
            ),
            key=lambda pair: pair[1],
            reverse=True,
        )[
            :top_n
        ]
    }

    return (
        len(
            candidate_top
            & reference_top
        )
        / top_n
    )


def summarize_against_reference(
    labels_by_k: Dict[
        str,
        List[LabeledExample],
    ],
    reference_k: str,
) -> List[Dict[str, Any]]:
    """Compare every tested resolution with the k=15 reference."""
    if not labels_by_k:
        return []

    if reference_k not in labels_by_k:
        raise KeyError(
            f"Reference resolution {reference_k!r} is not available."
        )

    reference_k_value = k_sort_key(
        reference_k
    )

    reference = {
        row.example_id: row.overall_label
        for row
        in labels_by_k[
            reference_k
        ]
    }

    summaries: List[
        Dict[str, Any]
    ] = []

    for k_name in sorted(
        labels_by_k,
        key=k_sort_key,
    ):
        rows = labels_by_k[
            k_name
        ]

        candidate = {
            row.example_id: row.overall_label
            for row
            in rows
        }

        common_ids = sorted(
            set(
                candidate
            )
            & set(
                reference
            )
        )

        candidate_values = [
            candidate[
                example_id
            ]
            for example_id
            in common_ids
        ]

        reference_values = [
            reference[
                example_id
            ]
            for example_id
            in common_ids
        ]

        if common_ids:
            absolute_differences = [
                abs(
                    candidate[
                        example_id
                    ]
                    - reference[
                        example_id
                    ]
                )
                for example_id
                in common_ids
            ]

            mean_abs_diff = statistics.mean(
                absolute_differences
            )

            max_abs_diff = max(
                absolute_differences
            )

        else:
            mean_abs_diff = float(
                "nan"
            )

            max_abs_diff = float(
                "nan"
            )

        k_value = k_sort_key(
            k_name
        )

        summaries.append(
            {
                "calibration_resolution": k_name,
                "reference_resolution": reference_k,
                "is_reference": (
                    k_name
                    == reference_k
                ),
                "num_calibration_points": (
                    k_value
                    ** 4
                ),
                "fraction_of_reference_grid": (
                    (
                        k_value
                        / reference_k_value
                    )
                    ** 4
                ),
                "num_target_examples": len(
                    common_ids
                ),
                "spearman_vs_reference": spearman(
                    candidate_values,
                    reference_values,
                ),
                "mean_abs_diff_vs_reference": (
                    mean_abs_diff
                ),
                "max_abs_diff_vs_reference": (
                    max_abs_diff
                ),
                "top_10_percent_overlap_vs_reference": (
                    top_fraction_overlap(
                        candidate,
                        reference,
                        fraction=0.10,
                    )
                ),
                "top_20_percent_overlap_vs_reference": (
                    top_fraction_overlap(
                        candidate,
                        reference,
                        fraction=0.20,
                    )
                ),
            }
        )

    return summaries


