def flatten_records(
    value: Any,
) -> List[Dict[str, Any]]:
    """Convert common JSON shapes into a list of dictionaries."""
    if isinstance(
        value,
        list,
    ):
        return [
            item
            for item
            in value
            if isinstance(
                item,
                dict,
            )
        ]

    if isinstance(
        value,
        dict,
    ):
        for key in (
            "records",
            "examples",
            "data",
            "results",
            "homes",
        ):
            nested = value.get(
                key
            )

            if isinstance(
                nested,
                list,
            ):
                return [
                    item
                    for item
                    in nested
                    if isinstance(
                        item,
                        dict,
                    )
                ]

        if all(
            isinstance(
                item,
                dict,
            )
            for item
            in value.values()
        ):
            records = []

            for key, item in value.items():
                record = dict(
                    item
                )

                record.setdefault(
                    "example_id",
                    key,
                )

                record.setdefault(
                    "id",
                    key,
                )

                records.append(
                    record
                )

            return records

    return []


def get_identifier(
    record: Dict[str, Any],
) -> Optional[str]:
    for key in (
        "example_id",
        "id",
        "home_id",
        "name",
        "folder",
        "address_folder",
        "simulation_name",
    ):
        value = record.get(
            key
        )

        if value is not None:
            return str(
                value
            )

    return None


def get_nested(
    record: Dict[str, Any],
    path: Sequence[str],
) -> Optional[Any]:
    current: Any = record

    for part in path:
        if (
            not isinstance(
                current,
                dict,
            )
            or part
            not in current
        ):
            return None

        current = current[
            part
        ]

    return current


def as_float(
    value: Any,
) -> Optional[float]:
    try:
        if value is None:
            return None

        return float(
            value
        )

    except (
        TypeError,
        ValueError,
    ):
        return None


