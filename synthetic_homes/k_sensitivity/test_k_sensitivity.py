#!/usr/bin/env python3

"""
Calibration-resolution sensitivity experiment.

This script evaluates how sensitive the final supervision scores are to the
resolution k of the synthetic ordinal calibration grid.

It requires a completed k=15 master calibration grid generated by:

    generate_calibration_grid.py

Expected default layout, relative to this script:

    generate_calibration_grid.py
    test_k_sensitivity.py

    calibration_grid/
    └── data/
        ├── calibration_meta.json
        ├── calibration_levels.json
        ├── summary_stats.json
        └── calibration_runtime.json

    dataset/
        └── ...

    k_sensitivity_results/
        └── ...

The calibration grid itself is generated only once at k=15. For each tested
resolution k in:

    {2, 3, 5, 7, 9, 11, 13, 15}

this script selects the corresponding approximately evenly spaced subset of
the k=15 master grid, recomputes the calibration statistics, and relabels the
same target examples.

The k=15 result is used as the high-resolution reference.

The script does not modify the source dataset or calibration data.

If no usable target examples can be loaded from dataset/, the script falls
back to using the k=15 calibration grid itself as the common target set.

Calibration metadata, EnergyPlus summaries, and runtime metadata are each
parsed only once. The analysis reports stage-level wall-clock timings rather
than using a persistent progress bar because no EnergyPlus simulations are run
during this experiment.

Default usage:

    python3 test_k_sensitivity.py

Optional explicit paths:

    python3 test_k_sensitivity.py \
        --calibration-dir ./calibration_grid \
        --dataset-dir ./dataset \
        --output-dir ./k_sensitivity_results
"""

