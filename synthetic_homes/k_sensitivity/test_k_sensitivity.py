def safe_std(
    values: Sequence[float],
) -> float:
    if len(
        values
    ) < 2:
        return 1.0

    std = statistics.pstdev(
        values
    )

    if math.isclose(
        std,
        0.0,
        abs_tol=1e-12,
    ):
        return 1.0

    return std


def build_scaler(
    rows: Sequence[RawExample],
    concept: str,
) -> Scaler:
    if concept == "hvac":
        text_values = [
            row.text_hvac
            for row
            in rows
        ]

        sim_values = [
            row.sim_hvac
            for row
            in rows
        ]

    elif concept == "insulation":
        text_values = [
            row.text_insulation
            for row
            in rows
        ]

        sim_values = [
            row.sim_insulation
            for row
            in rows
        ]

    else:
        raise ValueError(
            f"Unknown concept: {concept}"
        )

    return Scaler(
        text_mean=statistics.mean(
            text_values
        ),
        text_std=safe_std(
            text_values
        ),
        sim_mean=statistics.mean(
            sim_values
        ),
        sim_std=safe_std(
            sim_values
        ),
    )


def sigmoid(
    value: float,
) -> float:
    value = max(
        -3.0,
        min(
            3.0,
            value,
        ),
    )

    return (
        1.0
        / (
            1.0
            + math.exp(
                -value
            )
        )
    )


def fuse(
    text_value: float,
    sim_value: float,
    scaler: Scaler,
) -> float:
    text_z = (
        text_value
        - scaler.text_mean
    ) / scaler.text_std

    sim_z = (
        sim_value
        - scaler.sim_mean
    ) / scaler.sim_std

    return sigmoid(
        0.5
        * text_z
        + 0.5
        * sim_z
    )


