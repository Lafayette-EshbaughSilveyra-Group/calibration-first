def load_target_examples_from_dataset(
    dataset_dir: Path,
) -> List[RawExample]:
    """Extract reusable raw scorer values from the Synthetic Homes dataset."""
    if not dataset_dir.exists():
        print(
            f"      Dataset directory does not exist: "
            f"{dataset_dir}"
        )

        return []

    examples: List[
        RawExample
    ] = []

    seen: set[str] = set()

    json_files = sorted(
        dataset_dir.rglob(
            "*.json"
        )
    )

    print(
        f"      scanning {len(json_files):,} JSON files"
    )

    for path in json_files:
        try:
            raw_json = read_json(
                path
            )

        except (
            json.JSONDecodeError,
            OSError,
        ):
            continue

        records = flatten_records(
            raw_json
        )

        if (
            not records
            and isinstance(
                raw_json,
                dict,
            )
        ):
            records = [
                raw_json
            ]

        for index, record in enumerate(
            records
        ):
            if not isinstance(
                record,
                dict,
            ):
                continue

            identifier = (
                get_identifier(
                    record
                )
                or (
                    f"{path.parent.name}:"
                    f"{path.name}:"
                    f"{index}"
                )
            )

            text_hvac = extract_text_score(
                record,
                "hvac",
            )

            text_insulation = extract_text_score(
                record,
                "insulation",
            )

            sim_hvac = extract_sim_score(
                record,
                "hvac",
            )

            sim_insulation = extract_sim_score(
                record,
                "insulation",
            )

            if None in (
                text_hvac,
                text_insulation,
                sim_hvac,
                sim_insulation,
            ):
                continue

            if identifier in seen:
                continue

            seen.add(
                identifier
            )

            examples.append(
                RawExample(
                    example_id=identifier,
                    text_hvac=float(
                        text_hvac
                    ),
                    text_insulation=float(
                        text_insulation
                    ),
                    sim_hvac=float(
                        sim_hvac
                    ),
                    sim_insulation=float(
                        sim_insulation
                    ),
                )
            )

    print(
        f"      loaded {len(examples):,} target examples"
    )

    return examples


