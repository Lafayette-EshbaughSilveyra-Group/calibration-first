def label_examples(
    examples: Sequence[RawExample],
    k_name: str,
    hvac_scaler: Scaler,
    insulation_scaler: Scaler,
) -> List[LabeledExample]:
    labeled: List[
        LabeledExample
    ] = []

    for example in examples:
        hvac_label = fuse(
            example.text_hvac,
            example.sim_hvac,
            hvac_scaler,
        )

        insulation_label = fuse(
            example.text_insulation,
            example.sim_insulation,
            insulation_scaler,
        )

        overall_label = statistics.mean(
            (
                hvac_label,
                insulation_label,
            )
        )

        labeled.append(
            LabeledExample(
                example_id=example.example_id,
                k_name=k_name,
                hvac_label=hvac_label,
                insulation_label=insulation_label,
                overall_label=overall_label,
            )
        )

    return labeled


