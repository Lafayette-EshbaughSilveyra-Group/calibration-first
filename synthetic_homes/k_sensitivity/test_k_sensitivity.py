def nearest_level(
    parameter_name: str,
    value: Any,
    config: CalibrationConfig,
) -> Optional[int]:
    """Find the nearest master-grid level for one physical parameter."""
    numeric_value = as_float(
        value
    )

    if numeric_value is None:
        return None

    levels = config.parameter_levels[
        parameter_name
    ]

    index = min(
        range(
            len(levels)
        ),
        key=lambda i: abs(
            levels[i]
            - numeric_value
        ),
    )

    return (
        index
        + 1
    )


def extract_calibration_levels(
    record: Dict[str, Any],
    config: CalibrationConfig,
) -> Optional[Dict[str, int]]:
    """Read or infer one-based master-grid levels."""
    explicit = record.get(
        "ordinal_levels"
    )

    if isinstance(
        explicit,
        dict,
    ):
        explicit_levels = {
            "wall": as_float(
                explicit.get(
                    "wall_r_value"
                )
            ),
            "roof": as_float(
                explicit.get(
                    "roof_r_value"
                )
            ),
            "heating": as_float(
                explicit.get(
                    "hvac_heating_cop"
                )
            ),
            "cooling": as_float(
                explicit.get(
                    "hvac_cooling_cop"
                )
            ),
        }

        if all(
            value is not None
            for value
            in explicit_levels.values()
        ):
            levels = {
                key: int(
                    value
                )
                for key, value
                in explicit_levels.items()
            }

            if all(
                1
                <= value
                <= config.max_k
                for value
                in levels.values()
            ):
                return levels

    levels = {
        "wall": nearest_level(
            "wall_r_value",
            record.get(
                "wall_r_value"
            ),
            config,
        ),
        "roof": nearest_level(
            "roof_r_value",
            record.get(
                "roof_r_value"
            ),
            config,
        ),
        "heating": nearest_level(
            "hvac_heating_cop",
            record.get(
                "hvac_heating_cop"
            ),
            config,
        ),
        "cooling": nearest_level(
            "hvac_cooling_cop",
            record.get(
                "hvac_cooling_cop"
            ),
            config,
        ),
    }

    if any(
        value is None
        for value
        in levels.values()
    ):
        return None

    return {
        key: int(
            value
        )
        for key, value
        in levels.items()
        if value is not None
    }


def level_position(
    level: int,
    max_k: int,
) -> float:
    """Map a master-grid level to its semantic position in [0, 1]."""
    if not 1 <= level <= max_k:
        raise ValueError(
            f"level must be in 1..{max_k}; got {level}."
        )

    return (
        level
        - 1
    ) / (
        max_k
        - 1
    )


