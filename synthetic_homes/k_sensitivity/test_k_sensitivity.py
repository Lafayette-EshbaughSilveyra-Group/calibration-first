def evenly_spaced_level_indices(
    k: int,
    max_k: int,
) -> tuple[int, ...]:
    """
    Return k approximately evenly spaced one-based indices from 1..max_k.
    """
    if not 2 <= k <= max_k:
        raise ValueError(
            f"k must satisfy 2 <= k <= {max_k}; got {k}."
        )

    indices = tuple(
        int(
            round(
                1
                + i
                * (max_k - 1)
                / (k - 1)
            )
        )
        for i in range(k)
    )

    if len(
        set(indices)
    ) != k:
        raise RuntimeError(
            f"Could not construct {k} unique levels "
            f"from 1..{max_k}: {indices}"
        )

    return indices


def load_calibration_config(
    paths: ExperimentPaths,
) -> CalibrationConfig:
    """
    Load the exact parameter levels used by generate_calibration_grid.py.

    This avoids independently reconstructing the master grid in the analysis
    script.
    """
    levels_path = require_file(
        paths.calibration_data_dir
        / "calibration_levels.json"
    )

    payload = read_json(
        levels_path
    )

    if not isinstance(
        payload,
        dict,
    ):
        raise RuntimeError(
            f"{levels_path} must contain a JSON object."
        )

    try:
        max_k = int(
            payload[
                "max_k"
            ]
        )

    except (
        KeyError,
        TypeError,
        ValueError,
    ) as exc:
        raise RuntimeError(
            f"{levels_path} does not contain a valid 'max_k'."
        ) from exc

    if max_k != EXPECTED_MAX_K:
        raise RuntimeError(
            "This experiment expects a k=15 master calibration grid, "
            f"but calibration_levels.json reports max_k={max_k}."
        )

    raw_levels = payload.get(
        "parameter_levels"
    )

    if not isinstance(
        raw_levels,
        dict,
    ):
        raise RuntimeError(
            f"{levels_path} does not contain 'parameter_levels'."
        )

    parameter_levels: Dict[
        str,
        tuple[float, ...],
    ] = {}

    for parameter_name in REQUIRED_PARAMETERS:
        values = raw_levels.get(
            parameter_name
        )

        if not isinstance(
            values,
            list,
        ):
            raise RuntimeError(
                f"{levels_path} does not contain levels for "
                f"{parameter_name!r}."
            )

        try:
            converted = tuple(
                float(value)
                for value
                in values
            )

        except (
            TypeError,
            ValueError,
        ) as exc:
            raise RuntimeError(
                f"Invalid levels for {parameter_name!r}."
            ) from exc

        if len(
            converted
        ) != max_k:
            raise RuntimeError(
                f"{parameter_name!r} has {len(converted)} levels; "
                f"expected {max_k}."
            )

        parameter_levels[
            parameter_name
        ] = converted

    level_sets: Dict[
        str,
        tuple[int, ...],
    ] = {
        f"k{k}": (
            evenly_spaced_level_indices(
                k,
                max_k,
            )
        )
        for k
        in K_VALUES
    }

    return CalibrationConfig(
        max_k=max_k,
        k_values=K_VALUES,
        level_sets=level_sets,
        parameter_levels=parameter_levels,
        reference_k=f"k{max_k}",
    )


