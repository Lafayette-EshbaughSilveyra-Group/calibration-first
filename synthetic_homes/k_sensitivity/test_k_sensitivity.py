def k_sort_key(
    k_name: str,
) -> int:
    """Sort names such as k2, k11, and k15 numerically."""
    if not k_name.startswith(
        "k"
    ):
        raise ValueError(
            f"Invalid calibration-resolution name: {k_name}"
        )

    return int(
        k_name[
            1:
        ]
    )


def load_calibration_rows_by_k(
    master_rows: Sequence[
        tuple[
            RawExample,
            Dict[str, int],
        ]
    ],
    config: CalibrationConfig,
) -> Dict[
    str,
    List[RawExample],
]:
    """
    Subselect every tested grid from the common k=15 master calibration grid.
    """
    allowed_level_sets = {
        k_name: set(
            levels
        )
        for k_name, levels
        in config.level_sets.items()
    }

    rows_by_k: Dict[
        str,
        List[RawExample],
    ] = {
        name: []
        for name
        in config.level_sets
    }

    for row, levels in master_rows:
        level_values = tuple(
            levels.values()
        )

        for (
            k_name,
            allowed,
        ) in allowed_level_sets.items():
            if all(
                level in allowed
                for level
                in level_values
            ):
                rows_by_k[
                    k_name
                ].append(
                    row
                )

    for k_name in sorted(
        rows_by_k,
        key=k_sort_key,
    ):
        rows = rows_by_k[
            k_name
        ]

        expected = (
            len(
                config.level_sets[
                    k_name
                ]
            )
            ** 4
        )

        if not rows:
            raise RuntimeError(
                f"No calibration rows found for {k_name}. "
                "Check that the k=15 calibration run completed."
            )

        if len(
            rows
        ) != expected:
            print(
                f"      {k_name}: "
                f"{len(rows):,}/{expected:,} rows "
                "(WARNING: incomplete)"
            )

        else:
            print(
                f"      {k_name}: "
                f"{len(rows):,}/{expected:,} calibration rows"
            )

    return rows_by_k


