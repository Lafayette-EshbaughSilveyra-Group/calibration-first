@contextmanager
def stage(
    number: int,
    total: int,
    description: str,
) -> Iterator[None]:
    """Print and time one major analysis stage."""
    print(
        f"[{number}/{total}] "
        f"{description}...",
        flush=True,
    )

    started = (
        time.perf_counter()
    )

    try:
        yield

    finally:
        elapsed = (
            time.perf_counter()
            - started
        )

        print(
            f"      done in "
            f"{elapsed:.2f} s"
        )
        print()


