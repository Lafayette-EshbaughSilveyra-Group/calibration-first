def resolve_path(
    supplied: str | Path | None,
    default: Path,
) -> Path:
    """
    Resolve a command-line path.

    Explicit relative paths are interpreted relative to the shell's current
    working directory. Defaults are anchored to this script.
    """
    if supplied is None:
        return default.resolve()

    path = Path(
        supplied
    ).expanduser()

    if not path.is_absolute():
        path = (
            Path.cwd()
            / path
        )

    return path.resolve()


def build_paths(
    calibration_dir: str | Path | None,
    dataset_dir: str | Path | None,
    output_dir: str | Path | None,
) -> ExperimentPaths:
    calibration = resolve_path(
        calibration_dir,
        DEFAULT_CALIBRATION_DIR,
    )

    dataset = resolve_path(
        dataset_dir,
        DEFAULT_DATASET_DIR,
    )

    output = resolve_path(
        output_dir,
        DEFAULT_OUTPUT_DIR,
    )

    return ExperimentPaths(
        calibration_dir=calibration,
        calibration_data_dir=(
            calibration
            / "data"
        ),
        dataset_dir=dataset,
        output_dir=output,
    )


def read_json(
    path: Path,
) -> Any:
    with path.open(
        "r",
        encoding="utf-8",
    ) as handle:
        return json.load(
            handle
        )


def write_json(
    path: Path,
    value: Any,
) -> None:
    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    with path.open(
        "w",
        encoding="utf-8",
    ) as handle:
        json.dump(
            value,
            handle,
            indent=2,
            sort_keys=True,
        )

        handle.write(
            "\n"
        )


def require_file(
    path: Path,
) -> Path:
    if not path.exists():
        raise FileNotFoundError(
            "Required experiment file does not exist:\n"
            f"  {path}"
        )

    return path


